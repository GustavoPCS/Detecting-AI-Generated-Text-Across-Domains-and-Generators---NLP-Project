"""Controlled HTML-artifact ablation on the project's existing fixed dataset.

Replaces HTML formatting in all text rows while preserving document identities,
train/val/test assignments, human/machine labels and generator conditions. Trains
fresh TF-IDF LR and SVM models on the cleaned training texts. Does not rebuild
splits or length matching, so differences can be attributed to cleaning rather
than a changed sample pool.

Prerequisite: the untracked processed dataset.csv, generated by src.build_dataset.

Usage:
    python -m src.ablation_html --data data/processed/dataset.csv \\
        --out results/tfidf_html_ablation --n-boot 1000
"""
from __future__ import annotations

import argparse
import html
import re
from pathlib import Path

import numpy as np
import pandas as pd

from src import baselines_tfidf as B
from src import evaluate as E

# Named formatting elements only: avoid deleting mathematical/comparison text.
HTML_FORMAT_TAGS = re.compile(r"</?\s*(?:br|p|div|span|em|strong|b|i|ul|ol|li)\b[^>]*>", flags=re.I)


def strip_formatting(text: str) -> str:
    """Unescape entities, remove formatting tags, normalize whitespace."""
    unescaped = html.unescape(str(text))
    return re.sub(r"\s+", " ", HTML_FORMAT_TAGS.sub(" ", unescaped)).strip()


def clean_dataset(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    expected = {"text", "label", "source_id", "domain", "generator", "split"}
    if not expected <= set(df.columns):
        raise ValueError(f"Dataset missing columns: {sorted(expected - set(df.columns))}")
    cleaned = df.copy(deep=True)
    cleaned["text"] = df["text"].astype(str).map(strip_formatting)
    changed = df["text"].astype(str).to_numpy() != cleaned["text"].to_numpy()
    cleaned["clean_word_count"] = cleaned["text"].str.split().str.len()
    meta = df[["domain", "generator", "label"]].copy()
    meta["changed"] = changed
    stats = (meta.groupby(["domain", "generator", "label"], as_index=False)
             .agg(n_texts=("changed", "size"), n_changed=("changed", "sum"),
                  pct_changed=("changed", "mean")))
    return cleaned, stats


def compare_metrics(original: pd.DataFrame, cleaned: pd.DataFrame) -> pd.DataFrame:
    keys = ["method", "train_domain", "train_generator", "domain", "generator", "split"]
    for name, df in (("original", original), ("cleaned", cleaned)):
        if not set(keys + ["n", "macro_f1", "fpr", "tpr", "auroc"]) <= set(df.columns):
            raise ValueError(f"Missing columns in {name} metrics")
    merged = original.merge(cleaned, on=keys, suffixes=("_original", "_no_html"), validate="one_to_one")
    if len(merged) != len(original) or len(merged) != len(cleaned):
        raise AssertionError("Ablation must preserve every evaluation condition")
    if not (merged["n_original"] == merged["n_no_html"]).all():
        raise AssertionError("Ablation must preserve every test set's size")
    for metric in ("macro_f1", "fpr", "tpr", "auroc"):
        merged[f"delta_{metric}"] = merged[f"{metric}_no_html"] - merged[f"{metric}_original"]
    return merged


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--data", default="data/processed/dataset.csv")
    p.add_argument("--baseline-metrics", default="results/tfidf/metrics.csv")
    p.add_argument("--out", default="results/tfidf_html_ablation")
    p.add_argument("--n-boot", type=int, default=1000)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--domains", nargs="+", default=B.DOMAINS)
    p.add_argument("--generator", default="mistral-chat")
    p.add_argument("--test-generators", nargs="+", default=["mistral-chat", "llama-chat"])
    args = p.parse_args(argv)
    data_path = Path(args.data)
    if not data_path.exists():
        p.error(f"Missing {data_path}. Rebuild the original dataset with src.build_dataset first.")
    if args.n_boot < 0:
        p.error("--n-boot must be nonnegative")
    data = pd.read_csv(data_path)
    cleaned, stats = clean_dataset(data)
    # IMPORTANT: use the same source IDs/split/labels; cleaned text only.
    if not (data["source_id"].equals(cleaned["source_id"])
            and data["label"].equals(cleaned["label"])
            and data["split"].equals(cleaned["split"])):
        raise AssertionError("Text cleaning changed the sample population")
    res = B.run_baselines(cleaned, domains=args.domains, train_generator=args.generator,
                          test_generators=args.test_generators, seed=args.seed)
    out = B.save_outputs(res, args.out)
    new_metrics = E.run(res["test"], res["val"], n_boot=args.n_boot, seed=args.seed)
    new_metrics.to_csv(out / "metrics.csv", index=False)
    stats.to_csv(out / "cleaning_stats.csv", index=False)
    baseline = Path(args.baseline_metrics)
    if baseline.exists():
        comparison = compare_metrics(pd.read_csv(baseline), new_metrics)
        comparison.to_csv(out / "comparison.csv", index=False)
        print("Mean no-HTML - original change by method:")
        print(comparison.groupby("method")[["delta_macro_f1", "delta_fpr", "delta_auroc"]].mean()
            .round(3).to_string())
    print("Cleaning rates, by domain, generator and label:")
    print(stats.to_string(index=False))
    print(f"Saved no-HTML results to {out}")
    return new_metrics


if __name__ == "__main__":
    main()
